-- Вставка с обновлением: если религия с таким названием уже была (из V3), она приводится к настоящим данным
UPDATE religion r
SET description = s.description
FROM seed_religion s
WHERE r.name = s.name AND r.is_custom = FALSE;

INSERT INTO religion (name, description)
SELECT s.name, s.description
FROM seed_religion s
WHERE NOT EXISTS (
    SELECT 1 FROM religion r WHERE r.name = s.name AND r.is_custom = FALSE
);

-- Удаление временных религий V3, которых нет в настоящих данных.
-- Если на религию что-то ссылается (например, персонаж), она остаётся, а в журнале появляется сообщение.
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT id, name FROM religion
        WHERE is_custom = FALSE
          AND name NOT IN (SELECT name FROM seed_religion)
    LOOP
        BEGIN
            DELETE FROM religion WHERE id = r.id;
        EXCEPTION WHEN foreign_key_violation OR restrict_violation THEN
            RAISE NOTICE 'Религия "%" оставлена: на нее есть ссылки', r.name;
        END;
    END LOOP;
END $$;
