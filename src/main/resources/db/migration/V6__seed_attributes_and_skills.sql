-- Вставка с обновлением: если навык с таким названием уже был (из V3), он приводится к настоящим данным
INSERT INTO skill (name, description, attribute_id)
SELECT s.name, s.description, a.id
FROM seed_skill s
JOIN attribute a ON a.name = s.attr
ON CONFLICT (name) DO UPDATE
    SET description  = EXCLUDED.description,
        attribute_id = EXCLUDED.attribute_id;

-- 3. Удаление временных записей V3, которых нет в настоящих данных.
-- Если на запись что-то ссылается (внешний ключ RESTRICT), она остаётся, а в журнале появляется сообщение.
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT id, name FROM skill
        WHERE name NOT IN (SELECT name FROM seed_skill)
    LOOP
        BEGIN
            DELETE FROM skill WHERE id = r.id;
        EXCEPTION WHEN foreign_key_violation THEN
            RAISE NOTICE 'Навык "%" оставлен: на него есть ссылки', r.name;
        END;
    END LOOP;

    FOR r IN
        SELECT id, name FROM attribute
        WHERE name NOT IN ('Сила', 'Ловкость', 'Выносливость', 'Интеллект', 'Харизма', 'Воля', 'Ремесло')
    LOOP
        BEGIN
            DELETE FROM attribute WHERE id = r.id;
        EXCEPTION WHEN foreign_key_violation THEN
            RAISE NOTICE 'Атрибут "%" оставлен: на него есть ссылки', r.name;
        END;
    END LOOP;
END $$;
