-- Вставка с обновлением: если культура с таким названием уже была (из V3), она приводится к настоящим данным
UPDATE culture c
SET description = s.description
FROM seed_culture s
WHERE c.name = s.name AND c.is_custom = FALSE;

INSERT INTO culture (name, description)
SELECT s.name, s.description
FROM seed_culture s
WHERE NOT EXISTS (
    SELECT 1 FROM culture c WHERE c.name = s.name AND c.is_custom = FALSE
);

-- Удаление временных культур V3, которых нет в настоящих данных.
-- Если на культуру что-то ссылается (например, персонаж), она остаётся, а в журнале появляется сообщение.
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT id, name FROM culture
        WHERE is_custom = FALSE
          AND name NOT IN (SELECT name FROM seed_culture)
    LOOP
        BEGIN
            DELETE FROM culture WHERE id = r.id;
        EXCEPTION WHEN foreign_key_violation OR restrict_violation THEN
            RAISE NOTICE 'Культура "%" оставлена: на нее есть ссылки', r.name;
        END;
    END LOOP;
END $$;
